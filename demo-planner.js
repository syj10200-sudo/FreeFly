  function createDemoPlan(payload) {
    const start = new Date(payload.startDate + 'T12:00:00Z');
    const end = new Date(payload.endDate + 'T12:00:00Z');
    const numberOfDays = Math.round((end - start) / 86400000) + 1;
    if (!Number.isFinite(numberOfDays) || numberOfDays < 1 || numberOfDays > 14) throw new Error('날짜 오류');
    const city = places.find((item) => item.keys.some((key) => payload.destination.toLowerCase().includes(key)));
    const locationName = city ? city.name : payload.destination;
    const selectedStyles = payload.styles && payload.styles.length ? payload.styles : ['로컬투어'];
    const usedRouteIndices = new Set();
    const intro = city ? city.arrival : [
      '중심가·숙소 주변', '교통편에 맞춰 도착 후 숙소 체크인',
      '숙소 주변에서 점심 식사', '중심가 및 주변 거리 산책', '숙소에서 접근하기 편한 현지 식당 저녁'
    ];
    const outro = city ? city.departure : [
      '숙소·공항', '체크아웃 및 짐 정리', '출발 전 여유 있는 식사',
      '항공편·교통편에 맞춰 공항 또는 역으로 이동', '귀가'
    ];
    const days = [];

    for (let index = 0; index < numberOfDays; index++) {
      const date = new Date(start.getTime() + index * 86400000).toISOString().slice(0, 10);
      let route;
      let label;
      let notes = '관광지 운영시간·예약 가능 여부·교통편은 공식 안내 확인 필요.';
      if (index === 0) {
        route = intro;
        label = route[0] + ' · 도착 및 적응';
        notes = '첫날은 실제 도착 시각과 숙소 체크인 시간을 우선하세요.';
      } else if (index === numberOfDays - 1) {
        route = outro;
        label = route[0] + ' · 귀국 준비';
        notes = '항공편 출발 시각과 공항까지 이동 시간을 고려하세요.';
      } else {
        const style = selectedStyles[(index - 1) % selectedStyles.length];
        const choices = (city && city.routes) || [];
        let chosen = -1;
        for (let i = 0; i < choices.length; i++) {
          if (choices[i][0] === style && !usedRouteIndices.has(i)) { chosen = i; break; }
        }
        if (chosen === -1) {
          chosen = choices.findIndex((routeItem, i) => !usedRouteIndices.has(i));
        }
        if (chosen !== -1) {
          route = choices[chosen].slice(1);
          usedRouteIndices.add(chosen);
          if (usedRouteIndices.size === choices.length) usedRouteIndices.clear();
          label = route[0] + ' · ' + style;
        } else {
          route = buildGenericRoute(locationName, style, index).slice(1);
          label = route[0] + ' · ' + style;
        }
      }
      days.push({
        date, label,
        morning: index === 0 ? '항공편/교통편 도착 후 ' + route[1] : route[1],
        lunch: route[2],
        afternoon: numberOfDays === 1 ? '시간에 맞춰 주변 산책 후 귀가 준비' : route[3],
        evening: numberOfDays === 1 ? '출발 시간에 맞춰 귀가' : route[4],
        notes
      });
    }

    return {
      demo: true,
      title: locationName + ' ' + (numberOfDays - 1) + '박 ' + numberOfDays + '일 여행 초안',
      summary: payload.age + ' · ' + payload.gender + ' · ' + payload.relationship + ' ' + payload.people +
        ' · ' + selectedStyles.join(' + ') + '. ' +
        (travelNotes[payload.relationship] || '') +
        ' 주요 방문지를 지역별로 묶은 예시 일정입니다.',
      verificationNotice: '이 일정은 AI가 아닌 준비된 지역별 코스와 선택 조건으로 만든 샘플입니다. 운영시간·휴무·가격·예약 가능 여부·교통시간은 실시간 확인되지 않았습니다.',
      days
    };
  }

